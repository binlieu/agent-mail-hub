import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync, readFileSync, chmodSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { chromium } from 'playwright';
import { initialize } from '../dist/config.js';
import { startHub } from '../dist/server.js';

mkdirSync('.test-data', { recursive: true });
const directory = mkdtempSync(resolve('.test-data/browser-'));
const config = initialize(directory);
const hub = await startHub(directory, config, 0);
const admin = { role: 'admin' };
const planner = hub.store.createAgent(admin, { name: 'planner', project: 'demo', provider: 'simulated', model: 'ui-test', capabilities: [] });
const builder = hub.store.createAgent(admin, { name: 'builder', project: 'demo', provider: 'simulated', model: 'ui-test', capabilities: [] });
const question = hub.store.send({ role: 'agent', name: 'planner', project: 'demo' }, { to: 'builder', body: 'Please check the dashboard.', kind: 'question', idempotencyKey: 'ui-question' });
hub.store.send({ role: 'agent', name: 'builder', project: 'demo' }, { to: 'planner', body: '<img src=x onerror="window.UNSAFE=true"> This is literal message text.', kind: 'message', replyTo: question.id, idempotencyKey: 'ui-reply' });
const browser = await chromium.launch({ headless: true, ...(process.env.AMH_TEST_BROWSER ? { executablePath: process.env.AMH_TEST_BROWSER } : {}) }).catch(async error => { await hub.close(); throw error; });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
try {
  await page.goto(hub.url);
  await page.getByLabel('Dashboard administrator token').fill(config.adminToken);
  await page.getByRole('button', { name: 'Open dashboard' }).click();
  await page.locator('#message-count').filter({ hasText: '2' }).waitFor();
  assert.equal(await page.locator('.message-body img').count(), 0);
  assert.equal(await page.evaluate(() => window.UNSAFE), undefined);
  await page.getByRole('button', { name: 'View conversation' }).first().click();
  await page.locator('#thread .message-card').nth(1).waitFor();
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await page.getByRole('button', { name: 'Pause delivery' }).click();
  await page.getByRole('button', { name: 'Resume delivery' }).waitFor();
  assert.equal(hub.store.paused(), true);
  await page.getByRole('button', { name: 'Resume delivery' }).click();
  await page.getByRole('button', { name: 'Pause delivery' }).waitFor();
  assert.equal(hub.store.paused(), false);
  await page.getByLabel('Project', { exact: true }).last().fill('demo');
  await page.getByLabel('Recipient', { exact: true }).selectOption('builder');
  await page.getByLabel('Message', { exact: true }).fill('Human dashboard question');
  await page.getByLabel('Question', { exact: true }).check();
  await page.getByRole('button', { name: 'Send message' }).click();
  await page.getByText('Human dashboard question', { exact: true }).waitFor();
  const sent = hub.store.dashboard(admin, { after: 0, limit: 50 }).messages.find(message => message.body === 'Human dashboard question');
  assert.equal(sent.sender, '@human');
  hub.store.send({ role: 'agent', name: 'builder', project: 'demo' }, { to: '@human', body: 'Reply to the human', kind: 'message', idempotencyKey: 'ui-human-reply', replyTo: sent.id });
  await page.getByRole('button', { name: 'Refresh', exact: true }).click();
  await page.getByText('Reply to the human', { exact: true }).waitFor();
  await page.locator('.message-card').filter({ hasText: 'Reply to the human' }).getByRole('button', { name: 'Reply', exact: true }).click();
  assert.equal(await page.locator('#recipient').inputValue(), 'builder');
  await page.getByLabel('Message', { exact: true }).fill('Human response in the same thread');
  await page.getByRole('button', { name: 'Send message' }).click();
  await page.getByText('Human response in the same thread', { exact: true }).waitFor();
  const followup = hub.store.dashboard(admin, { after: 0, limit: 50 }).messages.find(message => message.body === 'Human response in the same thread');
  assert.equal(followup.conversation_id, sent.conversation_id);
  await page.getByText('Register an agent', { exact: true }).click();
  await page.getByLabel('Unique name').fill('browser-agent');
  await page.locator('#agent-project').fill('demo');
  await page.getByRole('button', { name: 'Create agent' }).click();
  await page.getByText('Agent created', { exact: true }).waitFor();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Save credentials' }).click();
  const download = await downloadPromise;
  const downloadPath = join(directory, 'browser-agent.json'); await download.saveAs(downloadPath); chmodSync(downloadPath, 0o600);
  const saved = JSON.parse(readFileSync(downloadPath, 'utf8'));
  assert.equal(saved.name, 'browser-agent'); assert.equal(saved.instanceId, config.instanceId);
  assert.equal(hub.store.authenticate(saved.token).name, 'browser-agent');
  const agentCard = page.locator('.agent-card').filter({ hasText: 'browser-agent' });
  await agentCard.getByRole('button', { name: 'Disable', exact: true }).click();
  await agentCard.getByText('Disabled', { exact: true }).waitFor();
  assert.equal(hub.store.authenticate(saved.token), null);
  await agentCard.getByRole('button', { name: 'Enable', exact: true }).click();
  await agentCard.getByRole('button', { name: 'Disable', exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Mobile layout should not overflow');
  await page.screenshot({ path: join(directory, 'mobile.png'), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.screenshot({ path: join(directory, 'desktop.png'), fullPage: true });
  await page.getByRole('button', { name: 'Sign out' }).click();
  await page.getByRole('heading', { name: 'Connect to your hub' }).waitFor();
  assert.equal(await page.evaluate(() => sessionStorage.getItem('amh.dashboard.token')), null);
  assert.deepEqual(errors, []);
  console.log(`PASS: dashboard sign-in, literal text/XSS, conversations, pause/resume, human send/reply, registration/download, disable/enable, mobile layout and sign-out.\nBrowser artifacts: ${directory}`);
} finally { await browser.close(); await hub.close(); }
